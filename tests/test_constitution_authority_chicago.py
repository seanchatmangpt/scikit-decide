def test_all_names_in___all___resolve_to_real_frozen_dataclasses():
    """Generic sweep over authority.__all__: every exported name is a real,
    constructible, frozen dataclass -- guards against __all__ drifting from
    the module's actual class definitions.
    """
    for name in authority.__all__:
        cls = getattr(authority, name)
        assert dataclasses.is_dataclass(cls)
        params = dataclasses.fields(cls)
        assert len(params) > 0

        # Construct with every field filled per its declared type.
        kwargs = {}
        for field in params:
            if field.type in ("tuple[str, ...]", "tuple[str,...]"):
                kwargs[field.name] = ("urn:example:1",)
            elif field.type in ("str | None", "Optional[str]"):
                kwargs[field.name] = "urn:example:functional:1"
            else:
                raise AssertionError(
                    f"unhandled field type {field.type!r} on {name}.{field.name} -- "
                    "extend this sweep, don't skip the field"
                )
        instance = cls(**kwargs)

        # Real state assertion: every field round-trips to what was passed.
        for field in params:
            assert getattr(instance, field.name) == kwargs[field.name]

        # Frozen dataclass instances refuse attribute assignment.
        first_field_name = params[0].name
        with pytest.raises(dataclasses.FrozenInstanceError):
            setattr(instance, first_field_name, getattr(instance, first_field_name))

