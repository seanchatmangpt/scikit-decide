"""Exercises the real ggen-manufactured module `autofde_lab.constitution.authority`.

No mocks, no stubs, no fakes: this test performs a real import of the manufactured
dataclasses and constructs real instances with every field explicitly filled, then
asserts on the real constructed state. The module itself is generated by `ggen sync
run` from `ontology/authority.ttl` (see the module's own docstring) -- this test is
the independently-runnable check that the generated shape still matches what the
ontology committed to.
"""
import dataclasses

import pytest

from autofde_lab.constitution import authority


def test_real_import_succeeds():
    """The module import itself is real -- no patching of sys.modules."""
    assert hasattr(authority, "__all__")
    assert authority.__all__ == ["Actuation", "AuthorityEnvelope"]


def test_actuation_real_fields_all_populated_with_representative_values():
    cls = getattr(authority, "Actuation")
    instance = cls(
        acts_on_environment=("urn:example:environment:1",),
        authorized_by="urn:example:authorityenvelope:1",
        exercises_capability=("urn:example:capability:1", "urn:example:capability:2"),
        realizes_commitment="urn:example:powlcommitment:1",
    )

    # Real state assertions on the real constructed instance -- not merely
    # "it constructed without raising".
    assert instance.acts_on_environment == ("urn:example:environment:1",)
    assert instance.authorized_by == "urn:example:authorityenvelope:1"
    assert instance.exercises_capability == (
        "urn:example:capability:1",
        "urn:example:capability:2",
    )
    assert instance.realizes_commitment == "urn:example:powlcommitment:1"

    # Field types match the ontology-derived shape: non-functional properties
    # are tuples of reference strings; functional properties are optional
    # single reference strings.
    assert isinstance(instance.acts_on_environment, tuple)
    assert all(isinstance(ref, str) for ref in instance.acts_on_environment)
    assert isinstance(instance.exercises_capability, tuple)
    assert isinstance(instance.authorized_by, str)
    assert isinstance(instance.realizes_commitment, str)


